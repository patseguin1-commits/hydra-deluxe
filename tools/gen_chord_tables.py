"""Code-generate src/core/chord_tables.cpp: the chord hash <-> code table.

Hydra gives every chord a short code string. Stored paths, the replay JSON
and the analysis chord counts all carry that code, so a code, once assigned,
never changes.

    py tools\\gen_chord_tables.py

The chord set is every chord a player can hit: an optional kick plus zero,
one or two pads (two hands, one foot):

  - Kick: normal, ghost or accent, each either a single or a 2x kick.
  - Red: normal, ghost or accent (Red is always a tom).
  - Yellow, Blue, Green: tom or cymbal, each normal, ghost or accent.

The first 551 chords (every chord with no kick or a normal kick) keep the codes the
Python-era hyencode.py hand-assigned; those codes are frozen in LEGACY below
because records in users' databases store them. A chord with a ghost or an
accent kick takes the code of the same chord with a normal kick, prefixed
with "g" (ghost) or "a" (accent). Every legacy code is either one character
or starts with "B", so the two sets cannot collide.

The hash is CPython's tuple hash over the five lanes (kick, red, yellow,
blue, green), each lane -1 when empty or 1000*color + 100*dyn + 10*cym + 2x
when filled. Python's own hash() computes it, and core/model.cpp reproduces
it bit for bit.

Idempotent: re-running with no change to this file produces a byte-identical
chord_tables.cpp. tests/test_chord_tables.cpp round-trips every entry.
"""

