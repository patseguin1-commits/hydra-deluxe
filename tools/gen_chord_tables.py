def note_hash(note):
    color, dyn, cym, is2x = note
    return 1000 * color + 100 * dyn + 10 * cym + is2x


def chord_hash(notes):
    slots = [-1] * 5
    for note in notes:
        slots[note[0] - 1] = note_hash(note)
    return hash(tuple(slots))


def all_chords():
    """Every chord: optional kick plus up to two pads, notes in lane order."""
    kick = [None] + [(KICK, dyn, TOM, is2x)
                     for dyn in (NORMAL, GHOST, ACCENT) for is2x in (0, 1)]
    red = [None] + [(RED, dyn, TOM, 0) for dyn in (NORMAL, GHOST, ACCENT)]

    def pad(color):
        return [None] + [(color, dyn, cym, 0)
                         for dyn in (NORMAL, GHOST, ACCENT)
                         for cym in (TOM, CYMBAL)]

    for lanes in itertools.product(kick, red, pad(YELLOW), pad(BLUE), pad(GREEN)):
        notes = tuple(n for n in lanes if n is not None)
        pads = sum(1 for n in notes if n[0] != KICK)
        if len(notes) >= 1 and pads <= 2:
            yield notes


def assign_codes():
    legacy_by_notes = {notes: code for code, notes in LEGACY.items()}
    if len(legacy_by_notes) != len(LEGACY):
        raise ValueError("LEGACY maps two codes to one chord")
    for code in LEGACY:
        if len(code) > 1 and code[0] != "B":
            raise ValueError(f"legacy code {code!r} would collide with a prefix")

    codes = {}
    for notes in all_chords():
        if notes in legacy_by_notes:
            codes[notes] = legacy_by_notes[notes]
            continue
        kick = notes[0]
        if kick[0] != KICK or kick[1] == NORMAL:
            raise ValueError(f"no legacy code for {notes}")
        normal_kick = ((KICK, NORMAL, kick[2], kick[3]),) + notes[1:]
        prefix = "g" if kick[1] == GHOST else "a"
        codes[notes] = prefix + legacy_by_notes[normal_kick]

    if len(set(codes.values())) != len(codes):
        raise ValueError("duplicate chord code")
    if set(LEGACY) - set(codes.values()):
        raise ValueError("a legacy chord fell out of the enumeration")
    return codes


def cpp_string(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= o <= 0x7E:
            out.append(ch)
        else:
            out.append(f"\\x{o:02x}")
    return "".join(out)


def cpp_int64(n):
    if not (INT64_MIN <= n <= INT64_MAX):
        raise ValueError(f"chord hash out of int64 range: {n}")
    if n == INT64_MIN:
        return "(-9223372036854775807LL - 1)"
    return f"{n}LL"


def main(out=None):
    out = pathlib.Path(out) if out else OUT
    codes = assign_codes()
    encode = {chord_hash(notes): code for notes, code in codes.items()}
    if len(encode) != len(codes):
        raise ValueError("two chords share a hash")
    items = sorted(encode.items())
    decode_items = sorted((code, notes) for notes, code in codes.items())

    lines = []
    lines.append("// GENERATED by tools/gen_chord_tables.py. Do not edit by hand;")
    lines.append("// re-run the generator instead.")
    lines.append("//")
    lines.append("// Chord hash -> code string, the reverse of what the scoring")
    lines.append("// code hashes a chord to, plus the code string -> note-field")
    lines.append("// list needed by Chord::from_code.")
    lines.append("")
    lines.append('#include "core/chord_tables.h"')
    lines.append("")
    lines.append("namespace hydra {")
    lines.append("namespace {")
    lines.append("")
    lines.append("struct ChordEncodeEntry {")
    lines.append("    int64_t hash;")
    lines.append("    const char* code;")
    lines.append("};")
    lines.append("")
    lines.append(f"// {len(items)} entries.")
    lines.append("const ChordEncodeEntry kEntries[] = {")
    for h, s in items:
        lines.append(f'    {{{cpp_int64(h)}, "{cpp_string(s)}"}},')
    lines.append("};")
    lines.append("")
    lines.append("struct ChordDecodeNote {")
    lines.append("    int color;")
    lines.append("    int dyn;")
    lines.append("    int cym;")
    lines.append("    int is2x;")
    lines.append("};")
    lines.append("struct ChordDecodeEntry {")
    lines.append("    const char* code;")
    lines.append("    const ChordDecodeNote* notes;")
    lines.append("    int count;")
    lines.append("};")
    lines.append("")
    for idx, (code, notes) in enumerate(decode_items):
        parts = [f"{{{c}, {d}, {cy}, {x}}}" for c, d, cy, x in notes]
        lines.append(
            f"const ChordDecodeNote kDecodeNotes{idx}[] = {{{', '.join(parts)}}};"
        )
    lines.append("")
    lines.append(f"// {len(decode_items)} entries.")
    lines.append("const ChordDecodeEntry kDecodeEntries[] = {")
    for idx, (code, notes) in enumerate(decode_items):
        lines.append(
            f'    {{"{cpp_string(code)}", kDecodeNotes{idx}, {len(notes)}}},'
        )
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("const std::unordered_map<int64_t, std::string>& chord_encode() {")
    lines.append("    static const std::unordered_map<int64_t, std::string> table = [] {")
    lines.append("        std::unordered_map<int64_t, std::string> m;")
    lines.append("        m.reserve(sizeof(kEntries) / sizeof(kEntries[0]) * 2);")
    lines.append("        for (const auto& e : kEntries)")
    lines.append("            m.emplace(e.hash, e.code);")
    lines.append("        return m;")
    lines.append("    }();")
    lines.append("    return table;")
    lines.append("}")
    lines.append("")
    lines.append("const std::string* encode_chord(int64_t hash) {")
    lines.append("    const auto& m = chord_encode();")
    lines.append("    auto it = m.find(hash);")
    lines.append("    return it == m.end() ? nullptr : &it->second;")
    lines.append("}")
    lines.append("")
    lines.append("const std::unordered_map<std::string, std::vector<ChordNoteFields>>&")
    lines.append("chord_decode() {")
    lines.append("    static const std::unordered_map<std::string,")
    lines.append("                                    std::vector<ChordNoteFields>>")
    lines.append("        table = [] {")
    lines.append("            std::unordered_map<std::string, std::vector<ChordNoteFields>> m;")
    lines.append("            m.reserve(sizeof(kDecodeEntries) / sizeof(kDecodeEntries[0]) * 2);")
    lines.append("            for (const auto& e : kDecodeEntries) {")
    lines.append("                std::vector<ChordNoteFields> notes;")
    lines.append("                notes.reserve(e.count);")
    lines.append("                for (int i = 0; i < e.count; ++i)")
    lines.append("                    notes.push_back({e.notes[i].color, e.notes[i].dyn,")
    lines.append("                                     e.notes[i].cym, e.notes[i].is2x});")
    lines.append("                m.emplace(e.code, std::move(notes));")
    lines.append("            }")
    lines.append("            return m;")
    lines.append("        }();")
    lines.append("    return table;")
    lines.append("}")
    lines.append("")
    lines.append("const std::vector<ChordNoteFields>* decode_chord(const std::string& code) {")
    lines.append("    const auto& m = chord_decode();")
    lines.append("    auto it = m.find(code);")
    lines.append("    return it == m.end() ? nullptr : &it->second;")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace hydra")
    lines.append("")

    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out} ({len(items)} encode, {len(decode_items)} decode entries)")


if __name__ == "__main__":
    import sys
    main(sys.argv[1] if len(sys.argv) > 1 else None)
